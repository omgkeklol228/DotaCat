/* Подставляет иконки в элементы <span class="ic-slot" data-icon="..."> */
window.fillIcons = function fillIcons(root = document) {
  root.querySelectorAll('.ic-slot[data-icon]').forEach((el) => {
    el.outerHTML = window.icon(el.dataset.icon);
  });
};
